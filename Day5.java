public class TipeDataPecahan {
    public static void main(String[] args) {
        // float wajib diakhiri huruf 'f'
        float nilaiFloat = 36.8f; 
        
        // double tidak perlu akhiran (tipe desimal default)
        double nilaiDouble = 22.74; 

        // Menampilkan nilai variabel
        System.out.println("Tipe float  : " + nilaiFloat);
        System.out.println("Tipe double : " + nilaiDouble);

    }
}
