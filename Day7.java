public class TipeDataStringUntukTeks {
    public static void main(String[] args) {
        
        // 1. Deklarasi dan Inisialisasi String
        String namaLengkap = "Arlin";
        String domisili = "Majene, Indonesia";
        String pesan = "Selamat belajar coding 100day! 🚀";

        // 2. Menampilkan isi String ke layar
        System.out.println("Nama     : " + namaLengkap);
        System.out.println("Tinggal  : " + domisili);
        System.out.println("Pesan    : " + pesan);
        
        // 3. Menggabungkan dua String (Concatenation)
        String sapaan = "Halo, " + namaLengkap + ". Selamat datang!";
        System.out.println(sapaan);
    }
}
