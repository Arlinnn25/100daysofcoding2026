public class TipeDataKarakter {
    public static void main(String[] args) {
        // Tipe data char: hanya untuk SATU karakter, diapit petik tunggal (' ')
        char huruf = 'B'; 
        char simbol = '@'; 

        // Tipe data boolean: hanya bisa bernilai true (benar) atau false (salah)
        boolean statusBekerja = false; 
        boolean statusBelajar = true;  

        // Menampilkan hasil isi variabel ke layar
        System.out.println("Huruf: " + huruf);
        System.out.println("Simbol: " + simbol);
        System.out.println("Sudah Bekerja? " + statusBekerja);
        System.out.println("Sudah Belajar? " + statusBelajar);
    }
}
