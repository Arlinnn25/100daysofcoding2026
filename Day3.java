public class EscapeSequence {
    public static void main(String[] args) {
        
        System.out.println("Baris 1\nBaris 2");           // \n = Membuat baris baru (pindah ke bawah)
        System.out.println("Nama:\tArlin");             // \t = Memberikan jarak renggang (tab horizontal)
        System.out.println("Dia berkata: \"Haii\"");     // \" = Menampilkan tanda kutip dua di dalam teks
        System.out.println("Karakter: \'A\'");           // \' = Menampilkan tanda kutip satu
        System.out.println("Folder: C:\\Data");          // \\ = Menampilkan satu tanda backslash (\)
    }
}
