public class FinalVariabel {
    public static void main(String[] args) {
        
        // final digunakan untuk nilai tetap dan tidak bisa diubah lagi
        final double Berat_Badan = 49.6;
        
        // nilai Berat_Badan tidak bisa diubah lagi
        System.out.println("Berat Badan :" + Berat_Badan);
        
        // contoh constanta lainnya adalah
        final int Usia = 19;
        
        // nilai dari usia tidak bisa diubah lagi
        System.out.println("Umur :" + Usia);
    }
}
