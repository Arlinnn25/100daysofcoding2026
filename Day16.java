public class ModulusAtauSisaBagi {
    public static void main(String[] args) {
        //Mendeklarasikan variabel tipe Integer
        int a = 10;
        int b = 3;
        //proses operator aritmatika modulus
        int hasil = a % b;
        //Menampilkan hasil modulus dari variabel a dan b
        System.out.println("Sisa bagi dari 10 % 3 adalah: " + hasil);
    }
}
